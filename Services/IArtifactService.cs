namespace abaci_bot.Services;

/// <summary>
/// Service abstraction for retrieving workflow run artifacts from GitHub Actions.
/// </summary>
public interface IArtifactService
{
    /// <summary>
    /// Downloads an artifact by ID from GitHub and unpacks RPM files to the specified directory.
    /// </summary>
    /// <param name="owner">Repository owner.</param>
    /// <param name="repo">Repository name.</param>
    /// <param name="artifactId">GitHub Actions artifact identifier.</param>
    /// <param name="destinationDirectory">Directory to extract files to.</param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>A list of extracted RPM file paths.</returns>
    Task<IReadOnlyList<string>> DownloadAndExtractRpmArtifactAsync(
        string owner, string repo, long artifactId, string destinationDirectory, CancellationToken ct = default);

    /// <summary>
    /// Discovers and downloads all RPM artifacts generated by a workflow run ID.
    /// </summary>
    Task<IReadOnlyList<string>> DownloadRunRpmArtifactsAsync(
        string owner, string repo, long runId, string destinationDirectory, CancellationToken ct = default);

    /// <summary>
    /// Downloads a baseline RPM from the configured stable mirror or release storage.
    /// </summary>
    Task<string?> DownloadBaselineRpmAsync(string packageName, string destinationDirectory, CancellationToken ct = default);
}
